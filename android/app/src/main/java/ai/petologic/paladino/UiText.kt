/** Resource-backed labels. Never apply to user messages, tool identifiers or saved instructions. */
@Composable internal fun tr(text:String,vararg args:Any):String {
 LocalConfiguration.current
 return LocalContext.current.uiText(text,*args)
}
internal fun Context.uiText(text:String,vararg args:Any):String {
 if(args.isEmpty()&&text !in UiLabels.ids){
  for((pattern,id) in UiLabels.templates){
   val match=pattern.matchEntire(text)?:continue
   return String.format(resources.configuration.locales[0],getString(id),*match.groupValues.drop(1).toTypedArray())
  }
 }
 val value=UiLabels.ids[text]?.let{getString(it)}?:text
 return if(args.isEmpty())value else String.format(resources.configuration.locales[0],value,*args)
}
@Composable internal fun sessionLabel(title:String):String = when {
 title=="First conversation"->tr(title)
 Regex("Conversation [0-9]+").matches(title)->tr("Conversation %1\$s",title.substringAfterLast(' '))
 else->title
}
internal fun Context.sessionText(title:String):String=when{
 title=="First conversation"->uiText(title)
 Regex("Conversation [0-9]+").matches(title)->uiText("Conversation %1\$s",title.substringAfterLast(' '))
 else->title
}
